func TestHumanTextDropsInjectedBlocks(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string // "" means: recognised as injected
	}{
		{"plain prompt", "Please deploy to openshift now", "Please deploy to openshift now"},
		{"system reminder only",
			"<system-reminder>\nAs you answer the user's question...\n</system-reminder>", ""},
		{"prompt then reminder",
			"yes please\n<system-reminder>Attribution for git commits</system-reminder>",
			"yes please"},
		{"reminder then prompt",
			"<system-reminder>Codebase instructions</system-reminder>\nNow fix the bug",
			"Now fix the bug"},
		{"continuation notice",
			"This session is being continued from a previous conversation that ran out of context.", ""},
		{"interrupted marker", "[Request interrupted by user for tool use]", ""},
		{"suggestion mode", "[SUGGESTION MODE: Suggest what the user might...", ""},
		{"image ref", "[Image #1]", ""},
		{"stepped away", "The user stepped away and is coming back. Resume.", ""},
		{"3-5 words probe", "Describe your most recent action in 3-5 words", ""},
		{"skill preamble", `Base directory for this skill: C:\Users\x\.claude\skills\foo`, ""},
		{"web page dump", "Web page content: --- GitHub - some/repo ...", ""},
		{"subagent directive", "Your directive: Research the dataset named X", ""},
		{"command echo", "<command-name>/clear</command-name>\n<command-message>clear</command-message>", ""},
		{"stdout echo", "<local-command-stdout>Set model to Opus</local-command-stdout>", ""},
		{"fork boilerplate", "<fork-boilerplate>\nYou are a worker fork.\n</fork-boilerplate>", ""},
		{"caveat block",
			"<local-command-caveat>Caveat: The messages below were generated by the user while running</local-command-caveat>", ""},

		// <session> WRAPS a real prompt: the content must survive. Dropping it silently
		// loses the first turn of every resumed session.
		{"session wrapper keeps content",
			"<session>\nHi Claude, we're back. Finalize the deck please.\n</session>",
			"Hi Claude, we're back. Finalize the deck please."},

		// Cross-session / teammate traffic: another AGENT talking, delivered as role:user text
		// with no enclosing wrapper. Measured on 5 of 101 sessions; on one 206-call session these
		// were 12 of 18 apparent turns.
		{"coordinator message",
			"The coordinator sent a message while you were working: Any update on the research?", ""},
		{"peer session message",
			"Another Claude session sent a message while you were working: " +
				`<agent-message from="a3136f2f935d5166c"> Yes, done. </agent-message>`, ""},
		{"agent-message envelope alone",
			`<agent-message from="a01709d1964697604">Received, thanks</agent-message>`, ""},
		{"cross-session envelope alone",
			`<cross-session-message from="worker">check the tests</cross-session-message>`, ""},

		{"whitespace normalised", "  fix   the\n\n bug  ", "fix the bug"},
		{"empty", "", ""},
		{"punctuation remnant", "  .  ", ""},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := HumanText(c.in)
			if got != c.want {
				t.Errorf("HumanText(%q)\n  got  %q\n  want %q", c.in, got, c.want)
			}
		})
	}
}

func TestConversationAnchorSurvivesCompaction(t *testing.T) {
	// The anchor is the advertised tool set, precisely because it does NOT scroll out of the
	// replayed window. Two calls from the same conversation, one before and one after the
	// earliest turn was compacted away, must still share an identity.
	mainTools := `[{"name":"Bash"},{"name":"Read"},{"name":"Write"},{"name":"Edit"}]`
	subTools := `[{"name":"Bash"},{"name":"Read"}]` // Explore: no Write, no Edit

	before := conversationAnchor(mainTools)
	after := conversationAnchor(mainTools)
	if before == "" {
		t.Fatal("a call advertising tools must have an anchor")
	}
	if before != after {
		t.Error("same tool set must give the same anchor across calls (compaction stability)")
	}
	if conversationAnchor(subTools) == before {
		t.Error("a restricted subagent tool set must not share the main thread's anchor")
	}
	// A WebFetch-fed thread advertises no tools at all; that is its signature, not a root.
	for _, empty := range []string{"", "  ", "[]", "null"} {
		if r := conversationAnchor(empty); r != "" {
			t.Errorf("empty tool set %q should yield no anchor, got %q", empty, r)
		}
	}
}

