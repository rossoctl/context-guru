func TestReconstructTurnsDeduplicatesAndOrders(t *testing.T) {
	mk := func(order string, texts ...string) Call {
		var msgs []Message
		for _, tx := range texts {
			msgs = append(msgs, Message{Role: "user",
				Parts: []Part{{Type: PartText, Content: tx}}})
		}
		return Call{Order: order, Messages: msgs, ToolDefs: mainToolDefs}
	}
	// Every call replays the whole conversation, which is the property being relied on.
	calls := []Call{
		mk("03", "first turn", "second turn", "third turn"),
		mk("01", "first turn"),
		mk("02", "first turn", "second turn"),
		mk("04", "first turn", "second turn", "third turn"),
	}
	got := ReconstructTurns(calls)
	if len(got) != 3 {
		t.Fatalf("want 3 de-duplicated turns, got %d: %+v", len(got), got)
	}
	want := []string{"first turn", "second turn", "third turn"}
	for i, w := range want {
		if got[i].Text != w {
			t.Errorf("turn %d: got %q want %q", i, got[i].Text, w)
		}
		if got[i].Sequence != i+1 {
			t.Errorf("turn %d: sequence %d want %d", i, got[i].Sequence, i+1)
		}
	}
	if got[0].FirstSeen != "01" {
		t.Errorf("FirstSeen should be the EARLIEST call carrying it, got %q", got[0].FirstSeen)
	}
}

