// mainToolDefs / subToolDefs stand in for a main thread's full tool list and a subagent's
// restricted one -- the anchor ReconstructTurns groups on.
const mainToolDefs = `[{"name":"Bash"},{"name":"Read"},{"name":"Write"},{"name":"Edit"},{"name":"Task"}]`

func subToolDefs(i int) string {
	return `[{"name":"Read"},{"name":"Grep"},{"agent":` + string(rune('A'+i)) + `}]`
}

func TestReconstructTurnsDeduplicatesAndOrders(t *testing.T) {
	mk := func(order string, texts ...string) Call {
		var msgs []Message
		for _, tx := range texts {
			msgs = append(msgs, Message{Role: "user",
				Parts: []Part{{Type: PartText, Content: tx}}})
		}
		return Call{Order: order, Messages: msgs, ToolDefs: mainToolDefs}
	}
	// Every call replays the whole conversation, which is the property being relied on.
	calls := []Call{
		mk("03", "first turn", "second turn", "third turn"),
		mk("01", "first turn"),
		mk("02", "first turn", "second turn"),
		mk("04", "first turn", "second turn", "third turn"),
	}
	got := ReconstructTurns(calls)
	if len(got) != 3 {
		t.Fatalf("want 3 de-duplicated turns, got %d: %+v", len(got), got)
	}
	want := []string{"first turn", "second turn", "third turn"}
	for i, w := range want {
		if got[i].Text != w {
			t.Errorf("turn %d: got %q want %q", i, got[i].Text, w)
		}
		if got[i].Sequence != i+1 {
			t.Errorf("turn %d: sequence %d want %d", i, got[i].Sequence, i+1)
		}
	}
	if got[0].FirstSeen != "01" {
		t.Errorf("FirstSeen should be the EARLIEST call carrying it, got %q", got[0].FirstSeen)
	}
}

func TestReconstructTurnsDropsSubagentRoots(t *testing.T) {
	var calls []Call
	// Main conversation: 20 calls, same root.
	for i := 0; i < 20; i++ {
		calls = append(calls, Call{Order: "a" + string(rune('a'+i)), ToolDefs: mainToolDefs,
			Messages: []Message{
				{Role: "user", Parts: []Part{{Type: PartText, Content: "real human turn"}}},
			}})
	}
	// Six one-off subagent threads, each its own root, each with genuine-looking user text.
	for i := 0; i < 6; i++ {
		calls = append(calls, Call{Order: "z" + string(rune('a'+i)), ToolDefs: subToolDefs(i),
			Messages: []Message{
				{Role: "user", Parts: []Part{{Type: PartText,
					Content: "Research benchmark number " + string(rune('A'+i))}}},
			}})
	}
	got := ReconstructTurns(calls)
	if len(got) != 1 {
		t.Fatalf("want only the main conversation's 1 turn, got %d: %+v", len(got), texts(got))
	}
	if got[0].Text != "real human turn" {
		t.Errorf("kept the wrong root: %q", got[0].Text)
	}
}

func TestReconstructTurnsMergesAcrossClear(t *testing.T) {
	// KNOWN AND ACCEPTED COST of anchoring on tool definitions: a /clear starts a second
	// conversation but does not change the advertised tool set, so both halves share an anchor
	// and are numbered as one sequence. 2 of 66 measured sessions look like this.
	//
	// The trade was measured, not assumed: first-text keying separated them correctly but
	// fragmented every long session at compaction, costing 38 turns corpus-wide against the
	// 2 sessions this merges. No turn is LOST here -- only the boundary between them.
	var calls []Call
	for i := 0; i < 10; i++ {
		calls = append(calls, Call{Order: "a" + string(rune('a'+i)), ToolDefs: mainToolDefs,
			Messages: []Message{
				{Role: "user", Parts: []Part{{Type: PartText, Content: "before the clear"}}},
			}})
	}
	for i := 0; i < 10; i++ {
		calls = append(calls, Call{Order: "b" + string(rune('a'+i)), ToolDefs: mainToolDefs,
			Messages: []Message{
				{Role: "user", Parts: []Part{{Type: PartText, Content: "after the clear"}}},
			}})
	}
	got := ReconstructTurns(calls)
	if len(got) != 2 {
		t.Fatalf("both turns must survive the merge, got %d: %v", len(got), texts(got))
	}
	if got[0].Text != "before the clear" || got[1].Text != "after the clear" {
		t.Errorf("order not preserved across the clear: %v", texts(got))
	}
	if got[0].Sequence != 1 || got[1].Sequence != 2 {
		t.Errorf("merged conversation numbers continuously, got %d,%d",
			got[0].Sequence, got[1].Sequence)
	}
}

