func TestReconstructTurnsDropsHelperCalls(t *testing.T) {
	// Claude Code's session-title generator replays the human's prompt inside <session>...</session>
	// on a call that advertises NO tools. HumanText correctly extracts the prompt, but the call is
	// a helper, not the conversation -- and adopting such calls was measured to add 13 turns of
	// which only 2 were real. So they are dropped, and this is the cost: a turn that exists ONLY
	// in a helper call is not recovered. 2 of 528 measured turns are lost this way.
	var calls []Call
	for i := 0; i < 20; i++ {
		calls = append(calls, Call{Order: "a" + string(rune('a'+i)), ToolDefs: mainToolDefs,
			Messages: []Message{
				{Role: "user", Parts: []Part{{Type: PartText, Content: "the real conversation"}}},
			}})
	}
	calls = append(calls, Call{Order: "zz", ToolDefs: "", Messages: []Message{
		{Role: "user", Parts: []Part{{Type: PartText,
			Content: "<session> I have comments about the ht </session> Write the title in the " +
				"predominant language of the session."}}},
	}})
	got := ReconstructTurns(calls)
	if len(got) != 1 {
		t.Fatalf("helper call must not contribute a turn, got %d: %v", len(got), texts(got))
	}
	if got[0].Text != "the real conversation" {
		t.Errorf("kept the wrong text: %q", got[0].Text)
	}
}

func TestToolCallsLiftedFromBody(t *testing.T) {
	msgs := []Message{
		{Role: "assistant", Parts: []Part{
			{Type: PartText, Content: "running it"},
			{Type: PartToolCall, ID: "toolu_bdrk_01Fr", Name: "Bash",
				Arguments: `{"command":"ls -la"}`},
		}},
		{Role: "tool", Parts: []Part{
			{Type: PartToolResponse, ID: "toolu_bdrk_01Fr", Response: "total 0\n"},
		}},
	}
	calls := ToolCalls(msgs)
	if len(calls) != 1 {
		t.Fatalf("want 1 tool call, got %d", len(calls))
	}
	if calls[0].Name != "Bash" || calls[0].CallID != "toolu_bdrk_01Fr" {
		t.Errorf("bad lift: %+v", calls[0])
	}
	res := ToolResults(msgs)
	if res["toolu_bdrk_01Fr"] != "total 0\n" {
		t.Errorf("result not joined by call id: %#v", res)
	}
	at := ToolCallAttrs(calls[0])
	if at[AttrToolName] != "Bash" {
		t.Error("tool_name not emitted under claude-record's key")
	}
	if at[AttrToolLifted] != true {
		t.Error("provenance marker missing: a lifted value must say it was lifted")
	}
	// Nothing here may claim success or duration.
	for _, forbidden := range []string{"success", "duration_ms"} {
		if _, bad := at[forbidden]; bad {
			t.Errorf("attribute %q must NOT be synthesised from a body", forbidden)
		}
	}
}

func TestDerivedTurnSpanNeverClaimsObservation(t *testing.T) {
	sp := DerivedTurnSpan("trace1", "span1", "parent1",
		ReconTurn{Sequence: 3, Text: "fix the bug", Root: "abc123"},
		time.Date(2026, 9, 10, 7, 18, 20, 896000000, time.UTC))

	if sp.Name == "claude_code.interaction" {
		t.Fatal("a reconstruction must not wear the observed span's name")
	}
	if sp.Name != SpanDerivedTurn {
		t.Errorf("span name %q, want %q", sp.Name, SpanDerivedTurn)
	}
	if sp.Attributes[AttrTurnDerived] != true {
		t.Error("derived marker missing")
	}
	if sp.Attributes[AttrTurnMethod] != TurnMethodBodyRecon {
		t.Error("method not recorded; a consumer cannot audit the provenance")
	}
	// The duration must be absent, not zero-with-meaning and not invented.
	if sp.StartTime != sp.EndTime {
		t.Error("a derived turn knows one instant; start and end must match")
	}
	for k := range sp.Attributes {
		if strings.Contains(k, "duration") {
			t.Errorf("attribute %q: turn duration is not knowable from the proxy", k)
		}
	}
}

// --- corpus scoring -------------------------------------------------------------------
//
// Scores the reconstruction against real collected sessions. Skips unless CG_RECORD_CORPUS
// points at a directory of *.otel.json, so the suite stays runnable without the data.

type corpusFile struct {
	Spans []struct {
		Name       string         `json:"name"`
		StartTime  string         `json:"start_time"`
		Attributes map[string]any `json:"attributes"`
	} `json:"spans"`
}

func TestCorpusReconstructionScore(t *testing.T) {
	dir := os.Getenv("CG_RECORD_CORPUS")
	if dir == "" {
		t.Skip("set CG_RECORD_CORPUS to a directory of *.otel.json to score against real data")
	}
	files, err := filepath.Glob(filepath.Join(dir, "*.otel.json"))
	if err != nil || len(files) == 0 {
		t.Skipf("no corpus files in %s", dir)
	}

	// Two denominators, because they answer different questions and only reporting one misleads:
	//
	//   happened = max(interaction.sequence) -- how many turns the human actually took.
	//   kept     = how many interaction spans survived in the file. claude-record loses turns to
	//              Jaeger eviction (issue #21): measured, 528 of 764 survive, and the missing ones
	//              are always a contiguous block from sequence 1.
	//
	// Scoring only against `happened` charges the reconstruction for turns whose bodies were
	// evicted too, and there is nothing left in the file to recover them from. Scoring only
	// against `kept` flatters it by ignoring those turns entirely. Both are reported.
	var happened, kept, recon, recovered, sessions int
	for _, fp := range files {
		raw, err := os.ReadFile(fp)
		if err != nil {
			continue
		}
		var cf corpusFile
		if json.Unmarshal(raw, &cf) != nil {
			continue
		}
		var calls []Call
		var gt []string
		maxSeq := 0
		for _, sp := range cf.Spans {
			if sp.Name == "claude_code.interaction" {
				if v, ok := sp.Attributes["interaction.sequence"]; ok {
					if f, ok := v.(float64); ok && int(f) > maxSeq {
						maxSeq = int(f)
					}
				}
				if up, ok := sp.Attributes["user_prompt"].(string); ok {
					gt = append(gt, normalizeSpace(up))
				}
				continue
			}
			body, ok := sp.Attributes["gen_ai.input.messages"].(string)
			if !ok {
				continue
			}
			var msgs []Message
			if json.Unmarshal([]byte(body), &msgs) != nil {
				continue
			}
			defs, _ := sp.Attributes["gen_ai.tool.definitions"].(string)
			calls = append(calls, Call{Order: sp.StartTime, Messages: msgs, ToolDefs: defs})
		}
		if maxSeq == 0 {
			continue
		}
		sessions++
		got := ReconstructTurns(calls)
		for _, g := range gt {
			for _, r := range got {
				if r.Text == g || strings.Contains(r.Text, g) || strings.Contains(g, r.Text) {
					recovered++
					break
				}
			}
		}
		happened += maxSeq
		kept += len(gt)
		recon += len(got)
	}
	if sessions == 0 {
		t.Skip("corpus had no sessions with interaction spans")
	}
	covPct := 100.0 * float64(recon) / float64(happened)
	crPct := 100.0 * float64(kept) / float64(happened)
	recallPct := 100.0 * float64(recovered) / float64(kept)
	t.Logf("sessions=%d turns_happened=%d", sessions, happened)
	t.Logf("  claude-record kept   : %d (%.1f%% of happened)", kept, crPct)
	t.Logf("  cg reconstructed     : %d (%.1f%% of happened)", recon, covPct)
	t.Logf("  recall of kept turns : %d/%d (%.1f%%)", recovered, kept, recallPct)

	// Guard both claims the comparison makes. Bounds sit below the measured 85.2% / 97.0% so
	// corpus drift does not fail the build, but a filter regression (which shifts these by tens
	// of points) does.
	if covPct < 75 || covPct > 115 {
		t.Errorf("coverage %.1f%% of turns that happened; filter likely regressed", covPct)
	}
	if recallPct < 90 {
		t.Errorf("recall of claude-record's kept turns is %.1f%%; the reconstruction is losing "+
			"turns whose bodies are present", recallPct)
	}
	// The headline claim: reconstruction beats claude-record's own surviving turn spans.
	// A TIE IS THE CEILING, NOT A FAILURE, when claude-record lost nothing: if every turn that
	// happened is present as an interaction span, no reconstruction can exceed it. The claim this
	// guards is about a corpus with eviction in it, so it only applies when kept < happened.
	// Measured 2026-10-01 on a lossless 3-turn dual-recorded session: recon == kept == happened.
	if kept < happened && recon <= kept {
		t.Errorf("reconstructed %d <= claude-record's kept %d (of %d that happened); the "+
			"comparison's central claim no longer holds on this corpus", recon, kept, happened)
	}
}

// --- helpers -------------------------------------------------------------------------

func texts(ts []ReconTurn) []string {
	out := make([]string, len(ts))
	for i, t := range ts {
		out[i] = t.Text
	}
	return out
}
